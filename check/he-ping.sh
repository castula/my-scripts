#!/bin/bash

# 定义 IP 地址列表
ips=(
    216.66.22.2 216.218.200.58 184.105.253.14 184.105.253.10 184.105.250.46 
    72.52.104.74 64.62.134.130 64.71.156.86 216.66.77.230 66.220.18.42 
    209.51.161.58 209.51.161.14 66.220.7.82 216.218.226.238 216.66.38.58 
    216.66.84.46 216.66.86.114 216.66.87.14 216.66.80.30 216.66.87.102 
    216.66.80.26 216.66.88.98 216.66.84.42 216.66.86.122 216.66.80.90 
    216.66.80.162 216.66.80.98 216.218.221.6 216.218.221.42 74.82.46.6 
    216.66.87.98 216.66.87.134 216.66.64.154 216.218.142.50
)

echo "IP 延迟 (ms)"

# 遍历 IP 地址并进行 ping 测试
for ip in "${ips[@]}"; do
    output=$(ping -c 2 "$ip" | grep "time=" | awk -F'time=' '{print $2}' | awk '{print $1}')
    
    if [ -n "$output" ]; then
        min_latency=$(echo "$output" | sort -n | head -1) # 取最小延迟
        if (( $(echo "$min_latency < 50" | bc -l) )); then
            echo "$ip $min_latency"
        fi
    fi
done
